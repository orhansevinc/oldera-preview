Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'
$Script:LocalIsWindows = ([System.Environment]::OSVersion.Platform -eq [System.PlatformID]::Win32NT)

function Get-LocalOriginRoot {
    return (Resolve-Path (Join-Path $PSScriptRoot '../..')).Path
}

function Get-LocalOriginStateDir {
    return (Join-Path $PSScriptRoot '.state')
}

function Get-LocalOriginEnvFile {
    return (Join-Path (Get-LocalOriginStateDir) '.env.local')
}

function Get-LocalOriginCurrentFile {
    return (Join-Path (Get-LocalOriginStateDir) 'current.json')
}

function Convert-ToComposePath([string]$Path) {
    return ([System.IO.Path]::GetFullPath($Path)).Replace('\\','/')
}

function Get-RandomHex([int]$Bytes = 32) {
    $buffer = New-Object byte[] $Bytes
    $rng = [System.Security.Cryptography.RandomNumberGenerator]::Create()
    try { $rng.GetBytes($buffer) } finally { $rng.Dispose() }
    return (($buffer | ForEach-Object { $_.ToString('x2') }) -join '')
}

function Get-Sha256([string]$Path) {
    return (Get-FileHash -Algorithm SHA256 -LiteralPath $Path).Hash.ToLowerInvariant()
}

function Read-KeyValueFile([string]$Path) {
    $map = @{}
    if (-not (Test-Path -LiteralPath $Path)) { return $map }
    foreach ($line in Get-Content -LiteralPath $Path) {
        $trim = $line.Trim()
        if (-not $trim -or $trim.StartsWith('#')) { continue }
        $idx = $trim.IndexOf('=')
        if ($idx -lt 1) { continue }
        $key = $trim.Substring(0,$idx)
        $value = $trim.Substring($idx+1)
        $map[$key] = $value
    }
    return $map
}

function Write-KeyValueFile([string]$Path, [hashtable]$Values) {
    $parent = Split-Path -Parent $Path
    New-Item -ItemType Directory -Force -Path $parent | Out-Null
    $lines = @('# Generated by deploy/local-origin/bootstrap.ps1. DO NOT COMMIT.')
    foreach ($key in ($Values.Keys | Sort-Object)) {
        $value = [string]$Values[$key]
        if ($value.Contains("`r") -or $value.Contains("`n")) { throw "Invalid multiline env value: $key" }
        $lines += "$key=$value"
    }
    [System.IO.File]::WriteAllLines($Path, $lines, [System.Text.UTF8Encoding]::new($false))
}


function Get-OptionalProperty($Object, [string]$Name) {
    if ($null -eq $Object) { return $null }
    $prop = $Object.PSObject.Properties[$Name]
    if ($null -eq $prop) { return $null }
    return $prop.Value
}

function Read-JsonFile([string]$Path) {
    return (Get-Content -Raw -LiteralPath $Path | ConvertFrom-Json)
}

function Write-JsonFile([string]$Path, $Object) {
    $parent = Split-Path -Parent $Path
    New-Item -ItemType Directory -Force -Path $parent | Out-Null
    $tmp = "$Path.tmp"
    $Object | ConvertTo-Json -Depth 100 | Set-Content -LiteralPath $tmp -Encoding utf8
    Move-Item -Force -LiteralPath $tmp -Destination $Path
}

function Get-ComposeBaseArgs([string]$EnvFile = (Get-LocalOriginEnvFile)) {
    $root = Get-LocalOriginRoot
    $envMap = Read-KeyValueFile $EnvFile
    $project = 'oldkoweb-local-origin'
    if ($envMap.ContainsKey('LOCAL_COMPOSE_PROJECT') -and $envMap['LOCAL_COMPOSE_PROJECT']) { $project = $envMap['LOCAL_COMPOSE_PROJECT'] }
    return @(
        'compose',
        '--project-name',$project,
        '--env-file',$EnvFile,
        '-f',(Join-Path $root 'docker-compose.ws09.yml'),
        '-f',(Join-Path $PSScriptRoot 'docker-compose.local-origin.yml')
    )
}

function Invoke-DockerCompose {
    param(
        [string[]]$Arguments,
        [string]$EnvFile = (Get-LocalOriginEnvFile),
        [switch]$Capture
    )
    $base = Get-ComposeBaseArgs -EnvFile $EnvFile
    if ($Capture) {
        $out = & docker @base @Arguments 2>&1
        if ($LASTEXITCODE -ne 0) { throw "docker compose failed: $($out -join [Environment]::NewLine)" }
        return $out
    }
    & docker @base @Arguments
    if ($LASTEXITCODE -ne 0) { throw "docker compose failed with exit code $LASTEXITCODE" }
}

function Get-LocalMode([string]$EnvFile = (Get-LocalOriginEnvFile)) {
    $envMap = Read-KeyValueFile $EnvFile
    if ($envMap.ContainsKey('LOCAL_ADMIN_MODE') -and $envMap['LOCAL_ADMIN_MODE'] -eq 'release') { return 'release' }
    return 'fixture'
}

function Get-ProfileArgs([string]$EnvFile = (Get-LocalOriginEnvFile)) {
    if ((Get-LocalMode $EnvFile) -eq 'release') { return @('--profile','real-admin') }
    return @('--profile','fixture-admin')
}

function Wait-ServiceHealthy([string]$Service, [int]$TimeoutSeconds = 120, [string]$EnvFile = (Get-LocalOriginEnvFile)) {
    $deadline = (Get-Date).AddSeconds($TimeoutSeconds)
    do {
        $composeBase = Get-ComposeBaseArgs $EnvFile
        $id = (& docker @composeBase 'ps' '-q' $Service 2>$null | Select-Object -First 1)
        if ($LASTEXITCODE -eq 0 -and $id) {
            $status = (& docker inspect --format '{{if .State.Health}}{{.State.Health.Status}}{{else}}{{.State.Status}}{{end}}' $id 2>$null | Select-Object -First 1)
            if ($status -eq 'healthy' -or $status -eq 'running') { return }
            if ($status -eq 'unhealthy' -or $status -eq 'exited' -or $status -eq 'dead') {
                throw "$Service entered state: $status"
            }
        }
        Start-Sleep -Seconds 2
    } while ((Get-Date) -lt $deadline)
    throw "Timeout waiting for $Service health"
}

function Test-Http([string]$HostName, [string]$Path, [int]$Port = 8088, [switch]$AllowBody) {
    $url = "http://$HostName`:$Port$Path"
    $args = @('-fsS','--max-time','10','--resolve',"$HostName`:$Port`:127.0.0.1",$url)
    if (-not $AllowBody) { $args += @('-o', $(if ($LocalIsWindows) {'NUL'} else {'/dev/null'})) }
    $curl = if ($LocalIsWindows) { 'curl.exe' } else { 'curl' }
    $out = & $curl @args 2>&1
    if ($LASTEXITCODE -ne 0) { throw "HTTP check failed: $url :: $($out -join ' ')" }
    if ($AllowBody) { return ($out -join "`n") }
}
